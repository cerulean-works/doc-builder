"""
Stages a build into a copy of the kit (contract C5): one `+page.svelte`/`+page.ts` route per page, redirect stubs for
sections without an index page, the docs assets in `static/` and the site metadata in `src/lib/generated/site.json`.
"""

import json
import shutil
from dataclasses import dataclass
from pathlib import Path

from .build_doc import PAGE_SUFFIXES
from .toctree import SECTIONS, TocPage, TocTree
from .utils import doc_md_url, find_root_git, mdx_to_markdown, page_route

ROUTES_DIR = Path("src") / "routes"
STATIC_DIR = Path("static")
SITE_JSON = Path("src") / "lib" / "generated" / "site.json"
# Files of the MDX build that are not docs assets.
NON_STATIC_FILES = ("objects.inv",)

PAGE_TS = """import {{ metadata }} from "./+page.svelte";

// Generated by doc-builder (contract C5). The layout reads this through page.data.
export const load = () => ({{
\tsection: {section},
\ttitle: {title},
\teditUrl: {edit_url},
\tmdUrl: {md_url},
\theadings: JSON.parse(metadata),
}});
"""

REDIRECT_TS = """import {{ redirect }} from "@sveltejs/kit";
import {{ base }} from "$app/paths";

// Generated by doc-builder (contract C5): this section has no `index` page, so its
// root redirects to the section's first entry.
export const load = () => {{
\tredirect(308, `${{base}}/{target}/`);
}};
"""

REDIRECT_SVELTE = "<!-- Generated by doc-builder: redirect stub, see +page.ts -->\n"


@dataclass
class Site:
    project: str
    version: str
    title: str
    description: str
    repo: str
    source_ref: str
    # path of the docs folder relative to the repository root, for edit links ("" when it is the root)
    docs_path: str = ""

    def to_json(self, toctree):
        return {
            "project": self.project,
            "title": self.title,
            "description": self.description,
            "version": self.version,
            "repo": self.repo,
            "sourceRef": self.source_ref,
            "toctree": toctree.with_urls(self.project, self.version),
        }


def get_docs_path_in_repo(doc_folder):
    """Path of `doc_folder` relative to the root of its git repository (its own name when it is not in one)."""
    doc_folder = Path(doc_folder).absolute()
    git_root = find_root_git(doc_folder)
    if git_root is None:
        return doc_folder.name
    relative = doc_folder.relative_to(git_root).as_posix()
    return "" if relative == "." else relative


def find_page_source(doc_folder, local):
    """The source file of the page `local`, relative to `doc_folder` (posix)."""
    for suffix in PAGE_SUFFIXES:
        if (Path(doc_folder) / f"{local}{suffix}").is_file():
            return f"{local}{suffix}"
    return f"{local}.md"


def edit_url(site, source_path):
    path = f"{site.docs_path.strip('/')}/{source_path}" if site.docs_path.strip("/") else source_path
    return f"https://github.com/{site.repo}/blob/{site.source_ref}/{path}"


def _js_string(value):
    return json.dumps(value, ensure_ascii=False)


def stage_page(dest_dir, mdx_dir, doc_folder, site, page: TocPage):
    """
    Writes the `+page.svelte` and `+page.ts` of `page`. Returns its Markdown export as `(path relative to the
    `/<project>/<version>/` base, markdown)`.
    """
    route = page_route(page.section, page.local)
    route_dir = Path(dest_dir) / ROUTES_DIR / route
    route_dir.mkdir(parents=True, exist_ok=True)
    content = (Path(mdx_dir) / f"{page.local}.mdx").read_text(encoding="utf-8")
    (route_dir / "+page.svelte").write_text(content, encoding="utf-8", newline="\n")
    page_ts = PAGE_TS.format(
        section=_js_string(page.section),
        title=_js_string(page.title),
        edit_url=_js_string(edit_url(site, find_page_source(doc_folder, page.local))),
        md_url=_js_string(doc_md_url(site.project, site.version, page.section, page.local)),
    )
    (route_dir / "+page.ts").write_text(page_ts, encoding="utf-8", newline="\n")
    return f"{route}.md", mdx_to_markdown(content)


def stage_section_redirects(dest_dir, toctree: TocTree):
    """Sections without an index page get a root route that redirects to their first entry."""
    for section in SECTIONS:
        first_page = toctree.first_page(section)
        if first_page is None or toctree.section_index(section) is not None:
            continue
        route_dir = Path(dest_dir) / ROUTES_DIR / section
        route_dir.mkdir(parents=True, exist_ok=True)
        target = page_route(section, first_page.local).replace("`", "\\`").replace("${", "\\${")
        (route_dir / "+page.ts").write_text(REDIRECT_TS.format(target=target), encoding="utf-8", newline="\n")
        (route_dir / "+page.svelte").write_text(REDIRECT_SVELTE, encoding="utf-8", newline="\n")


def stage_static(dest_dir, mdx_dir):
    """Copies the non-page files of the MDX build (images, etc.) to `static/`, keeping their relative path."""
    mdx_dir = Path(mdx_dir)
    for file in sorted(mdx_dir.rglob("*")):
        relative = file.relative_to(mdx_dir)
        if not file.is_file() or file.suffix == ".mdx" or relative.as_posix() in NON_STATIC_FILES:
            continue
        dest = Path(dest_dir) / STATIC_DIR / relative
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(file, dest)


def write_site_json(dest_dir, site, toctree):
    site_json = Path(dest_dir) / SITE_JSON
    site_json.parent.mkdir(parents=True, exist_ok=True)
    site_json.write_text(
        json.dumps(site.to_json(toctree), indent="\t", ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )


def clear_section_routes(dest_dir):
    for section in SECTIONS:
        section_dir = Path(dest_dir) / ROUTES_DIR / section
        if section_dir.is_dir():
            shutil.rmtree(section_dir)


def stage_site(dest_dir, mdx_dir, doc_folder, toctree: TocTree, site: Site):
    """
    Stages the MDX build in `mdx_dir` into `dest_dir` (a copy of the kit) per contract C5. Pages that are not in the
    toctree are not staged.

    Returns the Markdown exports, in toctree order, as `(path relative to the /<project>/<version>/ base, markdown)`.
    """
    clear_section_routes(dest_dir)
    markdown_exports = []
    for page in toctree.pages():
        if not (Path(mdx_dir) / f"{page.local}.mdx").is_file():
            # only possible when the toctree check is skipped (preview watch mode)
            print(f"Skipping `{page.local}`: it is in the toctree but does not exist.")
            continue
        markdown_exports.append(stage_page(dest_dir, mdx_dir, doc_folder, site, page))
    stage_section_redirects(dest_dir, toctree)
    stage_static(dest_dir, mdx_dir)
    write_site_json(dest_dir, site, toctree)
    return markdown_exports


def write_markdown_exports(output_dir, markdown_exports):
    for relative_path, content in markdown_exports:
        dest = Path(output_dir) / relative_path
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, encoding="utf-8", newline="\n")
